"""Halal labels of catalog ingredients and certified FairPrice products (docs/design/halal.md; ADR-0104).

Two committed data files:
- `data/ingredients/halal-labels-v1.json` (generated by `python -m app.data.halal_labels`, reviewed), with a
  person's corrections in `data/ingredients/halal-overrides-v1.json` applied last;
- `data/ingredients/fairprice-halal-v1.json`: whether a release-snapshot product carried FairPrice's "Halal"
  dietary attribute when it was observed.

Unknown is never halal: an ingredient with no label is `uncertain`, and a product with no observation is `None`.
"""

import json
from functools import lru_cache
from typing import Literal, TypedDict

from app.core.paths import data_root

LABELS_FILE = "ingredients/halal-labels-v1.json"
OVERRIDES_FILE = "ingredients/halal-overrides-v1.json"
CERTIFICATION_FILE = "ingredients/fairprice-halal-v1.json"

HalalLabelStatus = Literal["halal", "not_halal", "uncertain"]
RecipeHalalStatus = Literal["halal", "needs_certification", "not_halal", "uncertain"]


class HalalLabel(TypedDict):
    normalized_name: str
    status: HalalLabelStatus
    needs_certification: bool
    source: str
    reason: str


def _items(name: str) -> list[dict]:
    path = data_root() / name
    if not path.exists():
        return []
    return json.loads(path.read_text(encoding="utf-8"))["items"]


@lru_cache
def halal_labels() -> dict[str, HalalLabel]:
    """normalized_name -> label, the person's overrides applied over the generated labels."""
    labels = {item["normalized_name"]: item for item in _items(LABELS_FILE)}
    for item in _items(OVERRIDES_FILE):
        base = labels.get(item["normalized_name"], {"needs_certification": False})
        labels[item["normalized_name"]] = {**base, **item, "source": "human"}
    return labels


def needs_certification(name: str) -> bool:
    label = halal_labels().get(name)
    return bool(label and label["status"] == "halal" and label["needs_certification"])


def recipe_halal_status(ingredient_names) -> RecipeHalalStatus:
    """A recipe's status from its lines: any not halal, else any unknown, else any needing a certified product."""
    labels = halal_labels()
    found = [labels.get(name) for name in ingredient_names]
    if any(label is not None and label["status"] == "not_halal" for label in found):
        return "not_halal"
    if any(label is None or label["status"] == "uncertain" for label in found):
        return "uncertain"
    if any(label["needs_certification"] for label in found):
        return "needs_certification"
    return "halal"


@lru_cache
def release_halal_certification() -> dict[str, bool | None]:
    """FairPrice external_id -> True when its listing carried "Halal", else None (unknown, never False)."""
    path = data_root() / CERTIFICATION_FILE
    if not path.exists():
        return {}
    products = json.loads(path.read_text(encoding="utf-8"))["products"]
    return {external_id: (True if fact.get("halal_certified") else None) for external_id, fact in products.items()}


def product_certified(product_id: str) -> bool | None:
    """A frozen or fixture product id's offline certification: `fixture:` and the `@ingredient` suffix of a product
    shared by two ingredients are dropped, since the facts are keyed by FairPrice's own id."""
    return release_halal_certification().get(product_id.removeprefix("fixture:").split("@")[0])
